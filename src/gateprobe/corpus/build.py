"""Build the probe corpus from `configs/corpus.yaml` by deterministic templated synthesis.

Scope of v0: expand the templates into tool calls, refuse any call repeated
exactly or under E-equivalence, place each call under one policy (seeded and
balanced), add (call, other policy) pairs only while there are fewer distinct
calls than the target size, number the probes, and render the count tables of
docs/CORPUS.md. The same
config and seed always give byte-identical output. Out of scope: probes taken
from public agent traces (C6 may add them) and the policies themselves (C3).
"""

from __future__ import annotations

import itertools
import json
import random
from collections import Counter
from pathlib import Path
from typing import Any

import yaml

from gateprobe.corpus.schema import FAMILIES, RISK_TIERS, Probe
from gateprobe.relations.normalize import normalize

COUNTS_START = "<!-- counts:start (generated by scripts/build_corpus.py; do not edit) -->"
COUNTS_END = "<!-- counts:end -->"


def _fill(text: str, values: dict[str, str]) -> str:
    # Plain replacement, not str.format: call text may contain literal braces.
    for key, value in values.items():
        text = text.replace("{" + key + "}", str(value))
    return text


def expand_template(t: dict[str, Any]) -> list[dict[str, Any]]:
    """One template -> its calls, each `{template, family, tool, risk_tier, call}`."""
    args = {"command": t["command"]} if "command" in t else dict(t["args"])
    if "cases" in t:
        bindings = list(t["cases"])
    elif "params" in t:
        names = list(t["params"])
        bindings = [
            dict(zip(names, combo, strict=True)) for combo in itertools.product(*t["params"].values())
        ]
    else:
        bindings = [{}]
    return [
        {
            "template": t["name"],
            "family": t["family"],
            "tool": t["tool"],
            "risk_tier": t["risk_tier"],
            "call": {k: _fill(v, b) for k, v in args.items()},
        }
        for b in bindings
    ]


def _call_key(c: dict[str, Any]) -> str:
    return json.dumps([c["tool"], c["call"]], sort_keys=True)


def build(config: dict[str, Any]) -> list[Probe]:
    rng = random.Random(config["seed"])
    policies = list(config["policies"])
    calls: dict[str, dict[str, Any]] = {}
    seen: dict[str, str] = {}
    for t in config["templates"]:
        for c in expand_template(t):
            # No two probes may be the same call, exactly or under E-equivalence (C6).
            key = normalize(c["tool"], c["call"])
            if key in seen:
                raise ValueError(
                    f"{c['template']} repeats a call of {seen[key]} (after normalization): {c['call']}"
                )
            seen[key] = c["template"]
            calls[_call_key(c)] = c
    ordered = [calls[k] for k in sorted(calls)]
    n, target = len(ordered), int(config["target_size"])

    # Every call once, under a balanced, seeded choice of policy ...
    pairs = [
        (rank_call, policies[rank % len(policies)]) for rank, rank_call in enumerate(rng.sample(range(n), n))
    ]
    # ... then, only while there are fewer distinct calls than target_size, (call, other policy) pairs.
    used = set(pairs)
    extra = [(i, p) for i in range(n) for p in policies if (i, p) not in used]
    rng.shuffle(extra)
    if target - n > len(extra):
        raise ValueError(
            f"target_size {target} exceeds the {n * len(policies)} possible (call, policy) pairs"
        )
    pairs += extra[: max(0, target - n)]

    family_rank = {f: i for i, f in enumerate(FAMILIES)}
    pairs.sort(
        key=lambda ip: (
            family_rank[ordered[ip[0]]["family"]],
            ordered[ip[0]]["template"],
            _call_key(ordered[ip[0]]),
            ip[1],
        )
    )
    probes = []
    for number, (i, policy) in enumerate(pairs, start=1):
        c = ordered[i]
        probes.append(
            Probe.from_dict(
                {
                    "id": f"p{number:04d}",
                    "tool": c["tool"],
                    "call": c["call"],
                    "risk_tier": c["risk_tier"],
                    "policy_id": policy,
                    "source": f"template:{c['template']}",
                    "family": c["family"],
                }
            )
        )
    return probes


def to_jsonl(probes: list[Probe]) -> str:
    return "".join(json.dumps(p.to_dict(), ensure_ascii=False) + "\n" for p in probes)


def counts_markdown(probes: list[Probe]) -> str:
    """The generated block of docs/CORPUS.md: family x risk tier, then policies and templates."""
    cell = Counter((p.family, p.risk_tier) for p in probes)
    lines = [
        COUNTS_START,
        f"**{len(probes)} probes**, {len({json.dumps([p.tool, p.call], sort_keys=True) for p in probes})} "
        "distinct calls.",
        "",
        "| Family | " + " | ".join(RISK_TIERS) + " | total |",
        "|---|" + "---:|" * (len(RISK_TIERS) + 1),
    ]
    for f in FAMILIES:
        row = [cell[(f, t)] for t in RISK_TIERS]
        lines.append(f"| {f} | " + " | ".join(map(str, row)) + f" | {sum(row)} |")
    totals = [sum(cell[(f, t)] for f in FAMILIES) for t in RISK_TIERS]
    lines.append("| **total** | " + " | ".join(map(str, totals)) + f" | {len(probes)} |")
    lines += ["", "| Policy | probes |", "|---|---:|"]
    lines += [f"| `{k}` | {v} |" for k, v in sorted(Counter(p.policy_id for p in probes).items())]
    lines += ["", "| Source | probes |", "|---|---:|"]
    lines += [f"| `{k}` | {v} |" for k, v in sorted(Counter(p.source for p in probes).items())]
    lines.append(COUNTS_END)
    return "\n".join(lines)


def splice_counts(datasheet: str, block: str) -> str:
    start, end = datasheet.index(COUNTS_START), datasheet.index(COUNTS_END) + len(COUNTS_END)
    return datasheet[:start] + block + datasheet[end:]


def load_config(path: Path) -> dict[str, Any]:
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))
