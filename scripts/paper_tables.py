#!/usr/bin/env python3
"""Generate the paper's results table and case box from results/ only (R7a; no hand-typed numbers).

Writes paper/figures/flips.tex (F - f per gate x class with Newcombe 95% intervals, the floor with
its Wilson interval, labels and the Bonferroni mark) from results/x4-final/, and
paper/figures/case_box.tex (p_block per repeat, before / after) from results/x5-case-studies/. The
inputs shown in the box (call, policy rendering, context) come from the committed variant files.

    uv run python scripts/paper_tables.py [--case GATE:VARIANT_ID ...] [--check]

--check regenerates in memory and exits 1 if a committed file differs (the gate's test does this).
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "figures"
GATES = [
    ("jev", "Jev 1.14"),
    ("gpt-6-luna-decisions", "GPT-6 Luna Dec."),
    ("pplx-decider", "pplx-decider v1.2"),
    ("drex", "drex v1.5"),
    ("judge-claude", "Claude Opus 5.5 judge"),
    ("rules", "Rule set"),
]
CLASSES = "EMIAP"
# G3 decision 6 (human, 2026-10-20): 1E in the paper box; 2' (jev:p0122/inject_preapproved/0) is
# the video's pair, and the text describes it.
CASES = ["drex:p0109/policy_format/0"]
RENDERINGS = {"yaml": "YAML", "json": "JSON", "prose": "prose", "bullets": "bullets"}


def _pts(x: str) -> str:
    v = 100 * float(x)
    return ("+" if v >= 0 else "$-$") + f"{abs(v):.1f}"  # the sign survives rounding to 0.0


def _cell(r: dict[str, str]) -> str:
    body = f"{_pts(r['excess'])}\\,[{_pts(r['excess_lo'])},\\,{_pts(r['excess_hi'])}]"
    if r["label"] == "positive":
        body = f"\\textbf{{{body}}}" + ("$^\\dagger$" if r["positive_bonferroni"] == "True" else "")
    return body


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def flips_table(results: Path) -> str:
    rel = {(r["gate_id"], r["class"]): r for r in _rows(results / "relations.csv") if r["transform"] == "*"}
    floor = {r["gate_id"]: r for r in _rows(results / "floor.csv")}
    meta = _rows(results / "meta.csv")[0]
    lines = [
        f"% Generated by scripts/paper_tables.py from {results.name}/ -- do not edit by hand.",
        "\\begin{tabular}{@{}ll" + "c" * len(CLASSES) + "@{}}",
        "\\toprule",
        "Gate & Floor $f$ (\\%) & " + " & ".join(CLASSES) + " \\\\",
        "\\midrule",
    ]
    for gid, name in GATES:
        f = floor[gid]
        fl = f"{100 * float(f['f']):.2f}\\,[{100 * float(f['f_lo']):.2f},\\,{100 * float(f['f_hi']):.2f}]"
        cells = [_cell(rel[(gid, c)]) if (gid, c) in rel else "--" for c in CLASSES]
        lines.append(f"{name} & {fl} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    lines.append(
        f"% Bonferroni over {meta['bonferroni_tests']} class tests (z = {float(meta['z_bonferroni']):.2f})."
    )
    return "\n".join(lines) + "\n"


def _event(x5: Path, gate: str, vid: str) -> dict[str, str]:
    """The X5 row for one (gate, variant); duplicates in the append-only CSVs must agree."""
    found = [
        r
        for name in ("case1_events.csv", "case2_events.csv")
        for r in _rows(x5 / name)
        if r["gate_id"] == gate and r["variant_id"] == vid
    ]
    if not found:
        raise SystemExit(f"{gate}:{vid} is not an X5 event in {x5}")
    if len({(r["parent_reps"], r["variant_reps"]) for r in found}) > 1:
        raise SystemExit(f"{gate}:{vid} has disagreeing rows in {x5}")
    return found[0]


def _variants(variants: Path) -> dict[str, dict]:
    out = {}
    for src in ("generated.jsonl", "paraphrase.jsonl"):
        with (variants / src).open(encoding="utf-8") as f:
            out |= {v["id"]: v for v in map(json.loads, f)}
    return out


def _tt(s: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("_", "\\_"), ("~", "\\textasciitilde{}"), ("&", "\\&")):
        s = s.replace(a, b)
    return f"\\texttt{{{s}}}"


def _call(v: dict) -> str:
    return _tt(v["call"].get("command") or json.dumps(v["call"]))


def _differs(x: dict, y: dict) -> tuple[list[str], list[str]]:
    """Row labels naming only what the rewrite changed: the call, the policy rendering, the context."""
    rx, ry = [], []
    if x["call"] != y["call"]:
        rx.append(_call(x))
        ry.append(_call(y))
    if x["policy_rendering"] != y["policy_rendering"]:
        rx.append(f"policy as {RENDERINGS.get(x['policy_rendering'], x['policy_rendering'])}")
        ry.append(f"policy as {RENDERINGS.get(y['policy_rendering'], y['policy_rendering'])}")
    if x["context"] != y["context"]:
        rx.append(f"context: ``{x['context']}''" if x["context"] else "context: none")
        ry.append(f"context: ``{y['context']}''" if y["context"] else "context: none")
    return rx, ry


def _ps(reps: str) -> tuple[str, str]:
    """'deny 0.835/deny 0.835/deny 0.835' -> ('0.835 (x3)', 'deny'); p as recorded, never re-rounded."""
    pairs = [r.split() for r in reps.split("/")]
    ps = [p for _, p in pairs]
    while all("." in p and len(p.split(".")[1]) > 1 and p.endswith("0") for p in ps):
        ps = [p[:-1] for p in ps]  # drop a trailing zero only where every repeat has one
    shown = f"{ps[0]} ($\\times${len(ps)})" if len(set(ps)) == 1 else "/".join(ps)
    verdicts = [v for v, _ in pairs]
    top = max(sorted(set(verdicts)), key=verdicts.count)
    n = verdicts.count(top)
    return shown, top if n == len(verdicts) else f"{top} ({n}/{len(verdicts)})"


def case_box(cases: list[str], x5: Path, variants: Path) -> str:
    by_id = _variants(variants)
    lines = [
        f"% Generated by scripts/paper_tables.py from {x5.name}/ -- do not edit by hand.",
        "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.54\\columnwidth}rl@{}}",
        "\\toprule",
        "Rewrite & $p_\\mathrm{block}$, $R=3$ & Verdict \\\\",
    ]
    for n, case in enumerate(cases, start=1):
        gate, vid = case.split(":", 1)
        e = _event(x5, gate, vid)
        x, y = by_id[e["parent_id"]], by_id[vid]
        head = f"\\textit{{{f'({n}) ' if len(cases) > 1 else ''}{dict(GATES)[gate]}, {x['policy_id']}}}"
        if x["call"] == y["call"]:
            head += f": {_call(x)}"
        lines += ["\\midrule", f"\\multicolumn{{3}}{{@{{}}l}}{{{head}}} \\\\"]
        for label, reps in zip(_differs(x, y), (e["parent_reps"], e["variant_reps"]), strict=True):
            shown, verdict = _ps(reps)
            lines.append(f"{', '.join(label)} & {shown} & {verdict} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def render(cases: list[str], root: Path = ROOT) -> dict[str, str]:
    return {
        "flips.tex": flips_table(root / "results" / "x4-final"),
        "case_box.tex": case_box(cases, root / "results" / "x5-case-studies", root / "variants"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--case", action="append", help="GATE:VARIANT_ID, repeatable (default: G3's pairs)")
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed file is stale")
    args = parser.parse_args()
    out = render(args.case or CASES)
    if args.check:
        stale = [n for n, text in out.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
        print("stale: " + ", ".join(stale) if stale else "paper/figures is up to date")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in out.items():
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"wrote {', '.join(f'{OUT.relative_to(ROOT)}/{n}' for n in out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
