#!/usr/bin/env python3
"""Generate the paper's results table, case box and threshold figure from results/ only (R7a, R7b).

Writes paper/figures/flips.tex (F - f per gate x class with Newcombe 95% intervals, the floor with
its Wilson interval, labels and the Bonferroni mark) from results/x2-seven-gates/, and
paper/figures/case_box.tex (p_block per repeat, before / after) from results/x5-case-studies/. The
inputs shown in the box (call, policy rendering, context) come from the committed variant files.
Once results/r7b-calibration/ exists (the analysis with the H2 labels), it also writes
paper/figures/threshold.tex: for each gate, the labeled probes on the wrong side of tau = 0.5 (deny-labeled
ones let through, allow-labeled ones blocked), with its ECE. No number is typed by hand.

    uv run python scripts/paper_tables.py [--case GATE:VARIANT_ID ...] [--check]

--check regenerates in memory and exits 1 if a committed file differs (the gate's test does this).
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "figures"
GATES = [
    ("jev", "Jev 1.14"),
    ("gpt-6-luna-decisions", "GPT-6 Luna Dec."),
    ("pplx-decider", "pplx-decider v1.2"),
    ("drex", "drex v1.5"),
    ("judge-claude", "Claude Opus 5.5 judge"),
    ("judge-gemma", "Gemma 4 31B judge"),
    ("rules", "Rule set"),
]
CLASSES = "EMIAP"
# Table II names its columns in full, so the reader needs no other table to read it (human, 2026-10-22).
CLASS_NAMES = {
    "E": "Equivalence",
    "M": "Monotonicity",
    "I": "Irrelevance",
    "A": "Adversarial",
    "P": "Paraphrase",
}
# G3 decision 6 (human, 2026-10-20): 1E in the paper box; 2' (jev:p0122/inject_preapproved/0) is
# the video's pair, and the text describes it.
CASES = ["drex:p0109/policy_format/0"]
RENDERINGS = {"yaml": "YAML", "json": "JSON", "prose": "prose", "bullets": "bullets"}
CALIBRATION = "r7b-calibration"  # results/<this>/: gateprobe analyze with probes/labels.jsonl (R7b)
# The plan's figure 2 is Jev against the judge; the humans added the Gemma judge (2026-10-22).
# Short gate names for the threshold figure; its rows follow GATES.
SHORT = {
    "gpt-6-luna-decisions": "Luna",
    "pplx-decider": "pplx",
    "drex": "drex",
    "judge-claude": "Claude",
    "judge-gemma": "Gemma",
    "jev": "Jev",
    "rules": "Rule set",
}
GROUP_ENDS = ("drex", "judge-gemma")  # Table II: space after the decision models and after the judges
THROUGH = "D55E00"  # Okabe-Ito vermillion: deny-labeled probes let through; the blocked ones stay gray


def _num(v: float, digits: int = 1, sign: bool = False) -> str:
    """A minus on negatives and a plus on signed estimates; a value that rounds to zero is plain 0.0."""
    s = f"{abs(v):.{digits}f}"
    if float(s) == 0:
        return s
    return ("$-$" if v < 0 else "+" if sign else "") + s


def _cell(r: dict[str, str]) -> str:
    """The estimate only: bold when violated (interval above 0), a dagger under Bonferroni. The intervals
    stay in the released CSVs (human, 2026-10-22: one number per cell)."""
    v = 100 * float(r["excess"])
    est = _num(v, sign=True)
    # pad to the widest form (+10.5) so the centered numbers line up on the decimal point
    est = ("" if est[0] in "+$" else "\\phantom{+}") + ("\\phantom{0}" if abs(round(v, 1)) < 10 else "") + est
    if r["label"] == "positive":
        est = f"\\textbf{{{est}}}" + ("\\rlap{$^\\dagger$}" if r["positive_bonferroni"] == "True" else "")
    return est


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def flips_table(results: Path) -> str:
    rel = {(r["gate_id"], r["class"]): r for r in _rows(results / "relations.csv") if r["transform"] == "*"}
    floor = {r["gate_id"]: r for r in _rows(results / "floor.csv")}
    meta = _rows(results / "meta.csv")[0]
    lines = [
        f"% Generated by scripts/paper_tables.py from {results.name}/ -- do not edit by hand.",
        "\\begin{tabular}{@{}lc" + "c" * len(CLASSES) + "@{}}",
        "\\toprule",
        f" & & \\multicolumn{{{len(CLASSES)}}}{{c}}{{Flip rate above the noise floor (points)}} \\\\",
        f"\\cmidrule(l){{3-{2 + len(CLASSES)}}}",
        "Gate & Noise floor (\\%) & " + " & ".join(CLASS_NAMES[c] for c in CLASSES) + " \\\\",
        "\\midrule",
    ]
    for gid, name in GATES:
        cells = [_cell(rel[(gid, c)]) if (gid, c) in rel else "--" for c in CLASSES]
        lines.append(f"{name} & {_num(100 * float(floor[gid]['f']), 2)} & " + " & ".join(cells) + " \\\\")
        if gid in GROUP_ENDS:
            lines.append("\\addlinespace[3pt]")
    lines += ["\\bottomrule", "\\end{tabular}"]
    lines.append(
        f"% Bonferroni over {meta['bonferroni_tests']} class tests (z = {float(meta['z_bonferroni']):.2f})."
    )
    return "\n".join(lines) + "\n"


def _event(x5: Path, gate: str, vid: str) -> dict[str, str]:
    """The X5 row for one (gate, variant); duplicates in the append-only CSVs must agree."""
    found = [
        r
        for name in ("case1_events.csv", "case2_events.csv")
        for r in _rows(x5 / name)
        if r["gate_id"] == gate and r["variant_id"] == vid
    ]
    if not found:
        raise SystemExit(f"{gate}:{vid} is not an X5 event in {x5}")
    if len({(r["parent_reps"], r["variant_reps"]) for r in found}) > 1:
        raise SystemExit(f"{gate}:{vid} has disagreeing rows in {x5}")
    return found[0]


def _variants(variants: Path) -> dict[str, dict]:
    out = {}
    for src in ("generated.jsonl", "paraphrase.jsonl"):
        with (variants / src).open(encoding="utf-8") as f:
            out |= {v["id"]: v for v in map(json.loads, f)}
    return out


def _tt(s: str) -> str:
    for a, b in (("\\", "\\textbackslash{}"), ("_", "\\_"), ("~", "\\textasciitilde{}"), ("&", "\\&")):
        s = s.replace(a, b)
    return f"\\texttt{{{s}}}"


def _call(v: dict) -> str:
    return _tt(v["call"].get("command") or json.dumps(v["call"]))


def _differs(x: dict, y: dict) -> tuple[list[str], list[str]]:
    """Row labels naming only what the rewrite changed: the call, the policy rendering, the context."""
    rx, ry = [], []
    if x["call"] != y["call"]:
        rx.append(_call(x))
        ry.append(_call(y))
    if x["policy_rendering"] != y["policy_rendering"]:
        rx.append(f"policy as {RENDERINGS.get(x['policy_rendering'], x['policy_rendering'])}")
        ry.append(f"policy as {RENDERINGS.get(y['policy_rendering'], y['policy_rendering'])}")
    if x["context"] != y["context"]:
        rx.append(f"context: ``{x['context']}''" if x["context"] else "context: none")
        ry.append(f"context: ``{y['context']}''" if y["context"] else "context: none")
    return rx, ry


def _ps(reps: str) -> tuple[str, str]:
    """'deny 0.835/deny 0.835/deny 0.835' -> ('0.835 (x3)', 'deny'); p as recorded, never re-rounded."""
    pairs = [r.split() for r in reps.split("/")]
    ps = [p for _, p in pairs]
    while all("." in p and len(p.split(".")[1]) > 1 and p.endswith("0") for p in ps):
        ps = [p[:-1] for p in ps]  # drop a trailing zero only where every repeat has one
    shown = f"{ps[0]} ($\\times${len(ps)})" if len(set(ps)) == 1 else "/".join(ps)
    verdicts = [v for v, _ in pairs]
    top = max(sorted(set(verdicts)), key=verdicts.count)
    n = verdicts.count(top)
    return shown, top if n == len(verdicts) else f"{top} ({n}/{len(verdicts)})"


def case_box(cases: list[str], x5: Path, variants: Path) -> str:
    by_id = _variants(variants)
    lines = [
        f"% Generated by scripts/paper_tables.py from {x5.name}/ -- do not edit by hand.",
        "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.54\\columnwidth}rl@{}}",
        "\\toprule",
        "Rewrite & $p_\\mathrm{block}$, $R=3$ & Verdict \\\\",
    ]
    for n, case in enumerate(cases, start=1):
        gate, vid = case.split(":", 1)
        e = _event(x5, gate, vid)
        x, y = by_id[e["parent_id"]], by_id[vid]
        head = f"\\textit{{{f'({n}) ' if len(cases) > 1 else ''}{dict(GATES)[gate]}, {x['policy_id']}}}"
        if x["call"] == y["call"]:
            head += f": {_call(x)}"
        lines += ["\\midrule", f"\\multicolumn{{3}}{{@{{}}l}}{{{head}}} \\\\"]
        for label, reps in zip(_differs(x, y), (e["parent_reps"], e["variant_reps"]), strict=True):
            shown, verdict = _ps(reps)
            lines.append(f"{', '.join(label)} & {shown} & {verdict} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def _counts(bins: list[dict[str, str]]) -> tuple[int, int, int, int]:
    """(deny-labeled, let through, allow-labeled, blocked) at tau = 0.5. Bins 0-4 hold p < 0.5 exactly."""

    def count(rows: list[dict[str, str]], deny: bool) -> int:
        x = sum(int(b["n"]) * (float(b["accuracy"]) if deny else 1 - float(b["accuracy"])) for b in rows)
        if abs(x - round(x)) > 1e-3:
            raise SystemExit(f"bin shares do not give whole probes: {x}")
        return round(x)

    below = [b for b in bins if int(b["bin"]) < 5]
    above = [b for b in bins if int(b["bin"]) >= 5]
    return count(bins, True), count(below, True), count(bins, False), count(above, False)


def threshold_figure(cal: Path) -> str:
    """pgfplots diverging bars, one row per gate: deny-labeled probes with mean p_block below tau = 0.5
    (let through, left) and allow-labeled ones at or above it (blocked, right); the row label gives the ECE
    (its interval stays in calibration.csv)."""
    summary = {r["gate_id"]: r for r in _rows(cal / "calibration.csv")}
    bins = _rows(cal / "reliability.csv")
    gates = [g for g, _ in GATES if g in summary]
    rows = len(gates)
    labels = []
    for gate in gates:
        c = summary[gate]
        labels.append(f"{SHORT[gate]} {{\\scriptsize\\color{{black!55}}{float(c['ece']):.2f}}}")
    lines = [
        f"% Generated by scripts/paper_tables.py from {cal.name}/ -- do not edit by hand.",
        "\\begin{tikzpicture}",
        f"\\definecolor{{gp-through}}{{HTML}}{{{THROUGH}}}",
        "\\begin{axis}[scale only axis, width=0.52\\columnwidth, y=10pt, y dir=reverse,",
        f"  xmin=-8, xmax=17, ymin=-0.4, ymax={rows + 0.9}, axis x line=none, axis y line=left,",
        "  y axis line style={draw=none},",
        f"  ytick={{{','.join(str(i + 1) for i in range(rows))}}}, yticklabels={{{', '.join(labels)}}},",
        "  yticklabel style={font=\\footnotesize}, major tick length=0pt, clip=false,",
        "  xbar, bar width=6.5pt, bar shift=0pt]",
        "\\addplot[fill=gp-through, draw=none] coordinates {"
        + " ".join(
            f"({-_counts([b for b in bins if b['gate_id'] == g])[1]},{i + 1})" for i, g in enumerate(gates)
        )
        + "};",
        "\\addplot[fill=black!35, draw=none] coordinates {"
        + " ".join(
            f"({_counts([b for b in bins if b['gate_id'] == g])[3]},{i + 1})" for i, g in enumerate(gates)
        )
        + "};",
    ]
    for i, gate in enumerate(gates):
        deny, through, allow, blocked = _counts([b for b in bins if b["gate_id"] == gate])
        lines.append(
            f"\\node[anchor=east, font=\\scriptsize, xshift=-1pt] "
            f"at (axis cs:{-through},{i + 1}) {{{through}}};"
        )
        if blocked:
            lines.append(
                f"\\node[anchor=west, font=\\scriptsize, xshift=1pt] "
                f"at (axis cs:{blocked},{i + 1}) {{{blocked}}};"
            )
    lines += [
        f"\\draw[black!70] (axis cs:0,0.45) -- (axis cs:0,{rows + 0.5});",
        f"\\node[font=\\scriptsize, below] at (axis cs:0,{rows + 0.45}) {{$\\tau = 0.5$}};",
        "\\node[font=\\scriptsize, anchor=south east, text=gp-through] at (axis cs:-0.6,0.45) {let through};",
        "\\node[font=\\scriptsize, anchor=south east, text=black!55, xshift=-4pt] "
        "at (axis cs:-8,0.45) {ECE};",
        "\\node[font=\\scriptsize, anchor=south west, text=black!60] at (axis cs:0.6,0.45) {blocked};",
        "\\end{axis}",
        "\\end{tikzpicture}",
    ]
    return "\n".join(lines) + "\n"


def render(cases: list[str], root: Path = ROOT) -> dict[str, str]:
    out = {
        # G3 decision 4: X2 finished before the cut-off, so the table has seven gates (Bonferroni over 35).
        # Its six frozen gates equal results/x4-final byte for byte (the X2 report's freeze check).
        "flips.tex": flips_table(root / "results" / "x2-seven-gates"),
        "case_box.tex": case_box(cases, root / "results" / "x5-case-studies", root / "variants"),
    }
    cal = root / "results" / CALIBRATION
    if cal.exists():
        out["threshold.tex"] = threshold_figure(cal)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--case", action="append", help="GATE:VARIANT_ID, repeatable (default: G3's pairs)")
    parser.add_argument("--check", action="store_true", help="exit 1 if a committed file is stale")
    args = parser.parse_args()
    out = render(args.case or CASES)
    if args.check:
        stale = [n for n, text in out.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
        print("stale: " + ", ".join(stale) if stale else "paper/figures is up to date")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in out.items():
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"wrote {', '.join(f'{OUT.relative_to(ROOT)}/{n}' for n in out)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
